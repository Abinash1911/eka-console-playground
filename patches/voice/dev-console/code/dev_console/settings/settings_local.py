# Where a workspace's regional data lives, keyed by the JWT `r` claim:
# console_session/console_event (`pg_alias`), session annotations
# (`mysql_alias`) and matrix's session tables (`dynamo_region`). A region
# other than home also carries its connections: `pg` and `mysql` (HOST,
# NAME, USER, PASSWORD, optional PORT and SSL_CA), from which its DATABASES
# entries are built below, and `clickhouse` (host, port, database, user,
# password; home uses CLICKHOUSE) — so adding a region is one entry in this
# secret and no code. HOME_REGION holds everything else, and is what a token without
# `r` maps to. Absent from secrets => India only, exactly as before.
